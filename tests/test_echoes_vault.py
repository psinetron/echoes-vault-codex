    def test_generated_index_is_sorted_and_ignores_page_body_changes(self) -> None:
        self.run_cli("init")
        for filename, summary in (
            ("zeta.md", "Zeta knowledge."),
            ("alpha.md", "Alpha knowledge."),
        ):
            payload = {
                "filename": filename,
                "content": (
                    "---\ntype: note\nstack: []\nstatus: active\n"
                    f"summary: {summary}\n---\n\n# Page\n\nBody one.\n"
                ),
            }
            code, _, error = self.run_cli("upsert", "--payload", "-", stdin=payload)
            self.assertEqual(code, 0, error)

        index = self.workspace / "EchoesVault" / "index.md"
        before = index.read_text(encoding="utf-8")
        self.assertLess(before.index("[[alpha]]"), before.index("[[zeta]]"))

        page = self.workspace / "EchoesVault" / "pages" / "zeta.md"
        updated = {
            "filename": "zeta.md",
            "content": page.read_text(encoding="utf-8").replace("Body one.", "Body two."),
            "expectedSha256": echoes_vault.sha256_text(page.read_text(encoding="utf-8")),
        }
        code, output, error = self.run_cli("upsert", "--payload", "-", stdin=updated)
        self.assertEqual(code, 0, error)
        self.assertFalse(json.loads(output)["indexChanged"])
        self.assertEqual(index.read_text(encoding="utf-8"), before)

