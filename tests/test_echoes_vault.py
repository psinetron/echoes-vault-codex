        self.assertEqual((self.workspace / "CLAUDE.md").read_text(), first_claude)
        self.assertIn("Keep this.", first_agents)
        self.assertIn("Keep this too.", first_claude)
        self.assertEqual(first_agents.count(echoes_vault.AGENT_GUIDE_START), 1)
        self.assertEqual(first_claude.count(echoes_vault.AGENT_GUIDE_START), 1)

